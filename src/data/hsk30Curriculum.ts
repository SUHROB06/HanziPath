export const hsk30LessonTemplates: LessonTemplate[] = (Object.keys(themes) as unknown as HSK30Level[])
  .flatMap(levelKey => {
    const level = Number(levelKey) as HSK30Level
    return themes[level].flatMap((theme, chapterIndex) =>
      levelGrammar[level].map((grammarFocus, partIndex) => ({
        id: `hsk30-${level}-${chapterIndex + 1}-${partIndex + 1}`,
        system: '3.0' as const,
        level,
        officialLevelCategory: level <= 6 ? String(level) : '7-9',
        chapter: chapterIndex + 1,
        part: partIndex + 1,
        title: `${theme.title} · часть ${partIndex + 1}`,
        keywords: theme.keywords,
        grammar: grammarFocus,
        minutes: minutesByLevel[level],
      })),
    )
  })
